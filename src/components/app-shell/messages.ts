/** Both dictionaries, for tests and for hosts that need a shell word in their own text. */
export const SHELL_MESSAGES: Readonly<Record<ShellLocale, ShellMessages>> = { en, de };

/** The dictionary for a locale. Anything that is not German is English. */
export function shellMessages(locale: string | null | undefined): ShellMessages {
  if (typeof locale === 'string' && /^de(?:[-_]|$)/i.test(locale)) return de;
  return en;
}

/** Fills `{name}` placeholders. Unknown names stay as they are. */
export function fillMessage(template: string, values: Readonly<Record<string, string>>): string {
  return template.replace(/\{(\w+)\}/g, (whole, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? values[key] : whole
  );
}
